# 06-blocks.R
# Step 6 of PLAN-cross-org.md: measure the cross-organization candidate set
# before any cross-org run.
#
# Measured on the whole panel, not on one or two buckets as the plan first
# said: a block's size depends on the whole population (an EIN bucket holds 1%
# of the organizations, so its SMITH block is ~100x too small), and the counts
# below need only block sizes, never the pairs themselves.
#
# Part 1, per EIN bucket (one callr process each, restart-safe as in 05b):
#   synthid::person_blocking_keys() on the bucket's profiles ->
#   blocks/keys/bucket=NN/part-0.parquet   EMP_ID, pass, block_key
# These keys are also the input to the step 8 runner, which batches by surname.
#
# Part 2, the whole panel: the size of every block, and from it, per pass,
#   blocks       distinct blocks with 2+ people
#   memberships  person-block rows
#   comparisons  pairs generated by blocks within MAX_BLOCK (what
#                candidate_pairs() reports as n_comparisons, before pairs
#                repeated across passes and same-org pairs are removed)
#   dropped      blocks over MAX_BLOCK, which candidate_pairs() skips, and
#                the comparisons they would have generated
#   people       persons with at least one usable block (2..MAX_BLOCK)
# and the cost (comparisons) per surname key, for load-balancing step 8.
#
# Writes: SYNTHID_DIR/partvii-v3_1/blocks/block-sizes.parquet
#         dev/partvii-panel/blocks-summary.csv, blocks-dropped.csv,
#         blocks-surname-cost.csv
#
#   Rscript dev/partvii-panel/06-blocks.R [workers] [max_block_size, default 5000]

source("dev/partvii-panel/_panel.R")
build_step("06-blocks")   # build-log.csv
args <- commandArgs(trailingOnly = TRUE)
NW <- if (length(args) >= 1) as.integer(args[1]) else max(1L, parallel::detectCores(logical = FALSE) - 2L)
MAX_BLOCK <- if (length(args) >= 2) as.integer(args[2]) else 5000L

pv_prof <- file.path(pv_root, "profiles")
pv_blk  <- file.path(pv_root, "blocks")
pv_keys <- file.path(pv_blk, "keys")
pv_run  <- file.path(pv_blk, "runs")
for (d in c(pv_keys, pv_run)) dir.create(d, recursive = TRUE, showWarnings = FALSE)
part <- function(root, b) file.path(root, paste0("bucket=", b), "part-0.parquet")

BKTS <- sort(sub("^bucket=", "", basename(dirname(Sys.glob(file.path(pv_prof, "bucket=*", "part-0.parquet"))))))
stamp("%d buckets with profiles", length(BKTS))

# ---- part 1: blocking keys per bucket --------------------------------------------
interrupted <- ledger_recover(pv_run, "keys", pv_blk)
todo <- BKTS[!file.exists(part(pv_keys, BKTS))]
stamp("%d of %d buckets need blocking keys, %d workers", length(todo), length(BKTS), NW)

keys_bucket <- function(b, f_prof, f_keys, write_atomic) {
  suppressPackageStartupMessages({ library(arrow); library(synthid) })
  t0 <- Sys.time()
  p <- as.data.frame(read_parquet(f_prof, col_select = c("EMP_ID", "last_name_keys", "states", "cbsa", "ntee")))
  k <- synthid::person_blocking_keys(p)
  write_atomic(k, f_keys)
  list(bucket = b, persons = nrow(p), keys = nrow(k), secs = as.numeric(Sys.time() - t0, units = "secs"))
}

MIN_FREE_GB <- as.numeric(Sys.getenv("MIN_FREE_GB", "12"))
free_gb <- function() ps::ps_system_memory()$avail / 1e9
log_line <- function(...) cat(format(Sys.time(), "%Y-%m-%d %H:%M:%S"), "|", sprintf(...), "\n",
                              file = file.path(pv_run, "progress.log"), append = TRUE)
queue <- todo; running <- list(); failed <- character(0)
while (length(queue) || length(running)) {
  for (b in names(running)) {
    p <- running[[b]]
    if (p$is_alive()) next
    r <- tryCatch(p$get_result(), error = function(e) list(error = conditionMessage(e)))
    if (is.null(r$error)) {
      log_line("bucket %s done: %d persons -> %d keys in %.1f min", b, r$persons, r$keys, r$secs / 60)
      ledger_append(pv_run, "keys", b, "done", p$get_pid(), sprintf("%d keys", r$keys))
    } else {
      log_line("bucket %s FAILED: %s", b, r$error)
      ledger_append(pv_run, "keys", b, "failed", p$get_pid(), r$error)
      failed <- c(failed, b)
    }
    running[[b]] <- NULL
  }
  while (length(queue) && length(running) < NW && free_gb() > MIN_FREE_GB) {
    b <- queue[1]; queue <- queue[-1]
    running[[b]] <- callr::r_bg(keys_bucket, args = list(b = b, f_prof = part(pv_prof, b), f_keys = part(pv_keys, b),
                                write_atomic = write_parquet_atomic), supervise = TRUE)
    ledger_append(pv_run, "keys", b, "started", running[[b]]$get_pid())
    log_line("bucket %s started (%d running, %.0f GB free)", b, length(running), free_gb())
    Sys.sleep(2)
  }
  Sys.sleep(5)
}
if (length(failed)) stop("blocking keys failed for bucket(s) ", paste(failed, collapse = " "),
                         "; see ", file.path(pv_run, "progress.log"), " and re-run")
stamp("blocking keys present for all %d buckets", length(BKTS))

# ---- part 2: block sizes over the whole panel -------------------------------------
# All in data.table: the first version did the count and the join below in
# arrow's query engine, and Rscript crashed inside arrow.dll (0xc0000005) on
# the 81.6M-row join. Reading the keys whole needs ~10 GB, which is fine here.
t0 <- Sys.time()
keys <- rbindlist(lapply(BKTS, function(b) as.data.table(read_parquet(part(pv_keys, b)))))
sizes <- keys[, .N, by = .(pass, block_key)]
setnames(sizes, "N", "n")
stamp("%s distinct blocks from %s key rows in %.1f min", format(nrow(sizes), big.mark = ","),
      format(nrow(keys), big.mark = ","), as.numeric(Sys.time() - t0, units = "mins"))
sizes[, surname_key := tstrsplit(block_key, "|", fixed = TRUE, keep = 2L)]
write_parquet_atomic(as.data.frame(sizes), file.path(pv_blk, "block-sizes.parquet"))

pairs <- function(n) as.numeric(n) * (as.numeric(n) - 1) / 2
sizes[, usable := n >= 2L & n <= MAX_BLOCK]
summ <- sizes[, .(blocks = sum(n >= 2L), memberships = sum(n),
                  comparisons = sum(pairs(n)[usable]),
                  dropped_blocks = sum(n > MAX_BLOCK),
                  dropped_memberships = sum(n[n > MAX_BLOCK]),
                  dropped_comparisons = sum(pairs(n)[n > MAX_BLOCK]),
                  largest_block = max(n)), by = pass]

# Persons reaching at least one usable block, per pass and over all passes.
keys[sizes, usable := i.usable, on = "block_key"]
reach <- unique(keys[usable == TRUE, .(EMP_ID, pass)])
n_persons <- uniqueN(keys$EMP_ID)
summ <- merge(summ, reach[, .(people = .N), by = pass], by = "pass", all.x = TRUE)
summ[, people_share := round(people / n_persons, 4)]
pass_order <- names(synthid::blocking_passes())
summ <- summ[order(match(pass, pass_order))]
total <- summ[, .(pass = "ALL", blocks = sum(blocks), memberships = sum(memberships),
                  comparisons = sum(comparisons), dropped_blocks = sum(dropped_blocks),
                  dropped_memberships = sum(dropped_memberships), dropped_comparisons = sum(dropped_comparisons),
                  largest_block = max(largest_block), people = uniqueN(reach$EMP_ID))]
total[, people_share := round(people / n_persons, 4)]
summ <- rbind(summ, total)
summ[, `:=`(max_block_size = MAX_BLOCK, persons = n_persons)]
fwrite(summ, file.path(pv_repo, "blocks-summary.csv"))
print(summ)

dropped <- sizes[n > MAX_BLOCK][order(-n)][, .(pass, block_key, n, would_be_comparisons = pairs(n))]
fwrite(dropped, file.path(pv_repo, "blocks-dropped.csv"))
stamp("%d blocks over %d people; largest: %s (%s)", nrow(dropped), MAX_BLOCK,
      dropped$block_key[1], format(dropped$n[1], big.mark = ","))

# Step 8 batches by surname key: its cost is the comparisons of its usable blocks.
cost <- sizes[usable == TRUE, .(comparisons = sum(pairs(n)), blocks = .N), by = surname_key][order(-comparisons)]
cost[, share := comparisons / sum(comparisons)]
fwrite(cost, file.path(pv_repo, "blocks-surname-cost.csv"))
stamp("%s surname keys with a usable block; the costliest (%s) holds %.1f%% of all comparisons, the top 100 %.1f%%",
      format(nrow(cost), big.mark = ","), cost$surname_key[1], 100 * cost$share[1], 100 * sum(head(cost$share, 100)))
